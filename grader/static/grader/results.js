/*
This function calculates erros and hence the score or grade for each url inputted by the url as comapred with the property of model the app is currently opened on
Error percentages are calculated with formula (user-reference)/reference * 100 

Arguments : slider , number 
  - slider is the id of error selecting slider type input
  - number is the total number of urls that successfully returned properties (i.e. number of cards (tables) in results page)

*/


function compute_error(slider,number){

  //grab  user selected acceptable error rate
  var slider = document.getElementById(slider);
  document.getElementById('slider_value').innerHTML=slider.value;
  error=Number(slider.value);

  //grab reference data from table
  var resulttable= document.getElementById("reference");
  let data = [...resulttable.rows].map(t => [...t.children].map(u => u.innerText)) ;  

  var ref_mass= Number(data[1][0]);
  var ref_vol = Number(data[1][1]);
  var ref_surf=Number(data[1][2]);


  for (let i=0; i<number;i++ ){ //for property in each url 

    //find url data from table using table id . table id are autogenerated with format "table_1" 
    var resulttable= document.getElementById("table_"+i); 
    let data = [...resulttable.rows].map(t => [...t.children].map(u => u.innerText)) ;  
    
    var error_mass= Math.abs(Number(data[1][0]) - ref_mass) * 100 /  ref_mass; 
    var error_vol=Math.abs(Number(data[1][1]) - ref_vol) * 100 /  ref_vol;
    var error_surf=Math.abs(Number(data[1][2]) - ref_surf) * 100 /  ref_surf;

 
    if (error_mass >  error) {
      resulttable.rows[2].cells[0].innerHTML="&#x274C;"; //wrong
    }
    else{
      resulttable.rows[2].cells[0].innerHTML="&#x2705;"; //right
    }
    if (error_vol >  error) {
      resulttable.rows[2].cells[1].innerHTML="&#x274C";
    }
    else{
      resulttable.rows[2].cells[1].innerHTML="&#x2705;";
    }
    if (error_surf >  error) {
      resulttable.rows[2].cells[2].innerHTML="&#x274C";
    }
    else{
      resulttable.rows[2].cells[2].innerHTML="&#x2705;";
    }
  }

}