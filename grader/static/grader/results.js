/*
This function rounds off the data fromt the table to 6 decimal places
!! FUTURE WORK : round the floating points based on the user's desired rounding scheme !! 

Arguments :  num_of_parts, num_of_urls
  - num_of_parts is the total number of parts in the reference document 
  - num_of_urls is the total number of urls that successfully returned properties (i.e. number of cards (tables) in the results page)
*/

function round_off_table_contents(num_of_parts, num_of_urls){

  //grab reference data from table
  var precison = 6 ; //set the precison
  var reference_table= document.getElementById("reference");
  let usr_data = [...reference_table.rows].map(t => [...t.children].map(u => u.innerText)) ;  
  for (let i = 1; i<num_of_parts; i++){
    for( let j = 1; j < 5; j++){
      reference_table.rows[i].cells[j].innerHTML= Number(usr_data[i][j]).toFixed(precison);
    }
  }

for (let r = 0; r < num_of_urls; r++ ){ //for property in each url 
    //find url data from table using table id . table id are autogenerated with format "table_[count]" 
    var resulttable = document.getElementById("table_"+r); 
    let ref_data = [...resulttable.rows].map(t => [...t.children].map(u => u.innerText)) ;  

    for (let i = 1; i<ref_data.length; i++){
      for( let j = 1; j < 5; j++){
        resulttable.rows[i].cells[j].innerHTML = Number(ref_data[i][j]).toFixed(precison);
      }
    }
  }
}





/*
This function calculates erros and hence the score or grade for each url inputted by the user as comapred with the property of model the app is currently opened on
Error percentages are calculated with formula (user-reference)/reference * 100 

Arguments : slider , number 
  - slider is the id of error selecting slider type input
  - number is the total number of urls that successfully returned properties (i.e. number of cards (tables) in results page)

*/


function compute_error(slider, num_of_urls){
  //grab  user selected acceptable error rate
  var slider = document.getElementById(slider);
  document.getElementById('slider_value').innerHTML=slider.value;
  error=Number(slider.value);
  //grab reference data from table
  var reference_table= document.getElementById("reference");
  let usr_data = [...reference_table.rows].map(t => [...t.children].map(u => u.innerText)) ;  

for (let r = 0; r < num_of_urls; r++ ){ //for property in each url 
    //find url data from table using table id . table id are autogenerated with format "table_[count]" 
    var resulttable = document.getElementById("table_"+r); 
    let ref_data = [...resulttable.rows].map(t => [...t.children].map(u => u.innerText)) ;  
    //console.log("ref data length",ref_data.length);
    for (let i = 1; i<ref_data[r].length; i++){
      for( let j = 1; j < 5; j++){
        var usr_prop = Number(usr_data[i][j]);
        var ref_prop = Number(ref_data[i][j]);
        var Error_cell = Math.abs(ref_prop - usr_prop) * 100 / ref_prop;
        var x = resulttable.getElementsByTagName("td");
        if (Error_cell > error){
          x[j].className="red";
        }
        else{
          x[j].className="green";
        }
      }
    }
  }

}
   