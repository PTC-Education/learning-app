function compute_error(num_of_urls){
  /*
  This function calculates erros and hence the score or grade for each url inputted by the user as comapred with the property of model the app is currently opened on
  Error percentages are calculated with formula (user-reference)/reference * 100 

  Arguments : slider , number 
    - slider is the id of error selecting slider type input
    - number is the total number of urls that successfully returned properties (i.e. number of cards (tables) in results page)
  */
  //grab  user selected acceptable error rate
  var slider = document.getElementById("tolerance_slider");
  document.getElementById('slider_value').innerHTML=slider.value;
  error=Number(slider.value);

  //grab reference data from reference table
  var usr_table= document.getElementById("reference");
  var usr_number_of_parts = usr_table.getElementsByTagName("tr").length; //number of parts in url element 


  //checking the list of properties user wants to compare
  var mass_select = document.getElementById("mass_check").checked;
  var vol_select = document.getElementById("vol_check").checked;
  var surf_select = document.getElementById("surf_check").checked;
  var PMOI_select = document.getElementById("PMOI_check").checked;


  for (let r = 0; r < num_of_urls; r++ ){ //for property in each url 
      //find url data from table using table id . table id are autogenerated with format "table_[count]" 
      var ref_table = document.getElementById("table_"+r); 
      var ref_number_of_parts = ref_table.getElementsByTagName("tr").length; //number of parts in url element
      
      if(usr_number_of_parts == ref_number_of_parts){
        for (let i = 1; i < ref_number_of_parts; i++){
          var usr_mass = document.getElementById("usr_mass_" + i).innerHTML;
          var usr_vol = document.getElementById("usr_vol_" + i).innerHTML;
          var usr_surf = document.getElementById("usr_surf_" + i).innerHTML;
          var usr_PMOI = document.getElementById("usr_PMOI_" + i).innerHTML;


          var ref_mass = document.getElementById("ref_mass_"+ r + "_" + i).innerHTML;
          var ref_vol = document.getElementById("ref_vol_" +  r + "_" + i).innerHTML;
          var ref_surf = document.getElementById("ref_surf_" + r + "_" + i).innerHTML;
          var ref_PMOI = document.getElementById("ref_PMOI_" +  r + "_" + i).innerHTML;


          var Error_mass = Math.abs(ref_mass - usr_mass) * 100 / ref_mass;
          var Error_vol = Math.abs(ref_vol - usr_vol) * 100 / ref_vol;
          var Error_surf = Math.abs(ref_surf - usr_surf) * 100 / ref_surf;
          var Error_PMOI = Math.abs(ref_PMOI - usr_PMOI) * 100 / ref_PMOI;

          var score="";
          if(mass_select) {
            if(Error_mass > error){
              document.getElementById("ref_mass_"+ r + "_" + i).className="red";
              score = score + "&#x274C";
            }
            else{
              document.getElementById("ref_mass_"+ r + "_" + i).className="green";
              score = score + "&#x2705";
            }
          } 
          if(vol_select) {
            if(Error_vol > error){
              document.getElementById("ref_vol_"+ r + "_" + i).className="red";
              score = score + "&#x274C";
            }
            else{
              document.getElementById("ref_vol_"+ r + "_" + i).className="green";
              score = score + "&#x2705";
            }
          }

          if(surf_select) {
            if(Error_surf > error){
              document.getElementById("ref_surf_"+ r + "_" + i).className="red";
              score = score + "&#x274C";
            }
            else{
              document.getElementById("ref_surf_"+ r + "_" + i).className="green";
              score = score + "&#x2705";
            }
          }

          if(PMOI_select){
            if(Error_PMOI > error){
              document.getElementById("ref_PMOI_"+ r + "_" + i).className="red";
              score = score + "&#x274C";
            }
            else{
              document.getElementById("ref_PMOI_"+ r + "_" + i).className="green";
              score = score + "&#x2705";
            }
          }
        document.getElementById("ref_score_"+ r + "_" + i).innerHTML = score;
        }
      }
      else{
          var text=document.getElementById("error_message_"+r);
          text.innerHTML="Mismatched number of parts from the reference- Please make sure you have selected the right document";
          ref_table.style.display="none";
      }
    }
  }
   