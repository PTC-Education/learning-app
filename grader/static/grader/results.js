function reform_result(num_of_urls){

  //checking the list of properties user wants to compare
  var c = [];
  for( let i = 0; i< 4 ; i++){
    c[i] = document.getElementById("check_"+ i).checked;
  }
  for (let r = 0; r <= num_of_urls ; r++ ){
    for( let i = 0; i < 4 ; i++){
      if(!c[i]){
        document.getElementsByClassName('col_' + i)[r].style.visibility='collapse';
      }
      else{
      document.getElementsByClassName('col_' + i)[r].style.visibility='visible';
      }
    }
  }
  compute_error(num_of_urls);
}


function round_off_table_contents(num_of_parts, num_of_urls){
  var precison = 6 ; //set the precison 
  for (let i = 1; i < num_of_parts; i++){
    //round off data for each part in the user document 
    for (let p = 0; p <4; p++){
      var data = document.getElementById("usr_" + p + "_" + i).innerHTML;
      document.getElementById("usr_" + p + "_" + i).innerHTML = Number(data).toFixed(precison);
    }
  }
  //round off data for each part in the results table 
  for (let r = 0; r < num_of_urls ; r++ ){ 
      //find url data from table using table id . table id are autogenerated with format "table_[count]" 
      var ref_table = document.getElementById("table_" + r); 
      var ref_number_of_parts = ref_table.getElementsByTagName("tr").length;
      //for each part 
      for (let i = 1; i < ref_number_of_parts; i++){
        //for each column
        for (let p = 0; p <4; p++){
          var data = document.getElementById("ref_" + p + "_" + r + "_" + i).innerHTML;
          document.getElementById("ref_" + p + "_" + r + "_" + i).innerHTML = Number(data).toFixed(precison);
        }
      }
    }
}




function compute_error(num_of_urls){
  /*
  This function calculates erros and hence the score or grade for each url inputted by the user as comapred with the property of model the app is currently opened on
  Error percentages are calculated with formula (user-reference)/reference * 100 

  Arguments : slider , number 
    - slider is the id of error selecting slider type input
    - number is the total number of urls that successfully returned properties (i.e. number of cards (tables) in results page)
  */
  //grab  user selected acceptable error rate
  var slider = document.getElementById("tolerance_slider");
  document.getElementById('slider_value').innerHTML=slider.value;
  error=Number(slider.value);

  //grab reference data from reference table
  var usr_table= document.getElementById("reference");
  var usr_number_of_parts = usr_table.getElementsByTagName("tr").length; //number of parts 

  //checking the list of properties user wants to compare
  c = []; //blank array to store check box info
  for( let i = 0; i< 4 ; i++){
    c[i] = document.getElementById("check_"+ i).checked;
  }

  for (let r = 0; r < num_of_urls; r++ ){ //for property in each url 
      //find url data from table using table id . table id are autogenerated with format "table_[count]" 
      var ref_table = document.getElementById("table_" + r); 
      var ref_number_of_parts = ref_table.getElementsByTagName("tr").length; //number of parts
      
      var score = 0;
      for (let i = 1; i < Math.min(usr_number_of_parts, ref_number_of_parts) ; i++){
        for (let p = 0; p < 4; p++){
          //get data for usr doc
          var usrdata = document.getElementById("usr_" + p + "_" + i).innerHTML;
            //get data for url docs
          var refdata = document.getElementById("ref_" + p + "_" + r + "_" + i).innerHTML;
          //calculate error
          var errdata = Math.abs(refdata - usrdata) * 100 / usrdata;
          
          if(c[p]){ //calculate error only if the correspnding checkbox is clicked
            if (errdata > error){
              document.getElementById("ref_" + p + "_" + r + "_" + i).className = "red";
              score = score + 1;    
            }
            else{
              document.getElementById("ref_" + p + "_" + r + "_" + i).className = "green";
            }
          }   
        }
      }

      if(score > 0){
        document.getElementById("ref_score_"+ r).innerHTML = "&#x274C";
      }
      else{
        document.getElementById("ref_score_"+ r).innerHTML = "&#x2705";
      }

      
      if(usr_number_of_parts != ref_number_of_parts){
          var text=document.getElementById("error_message_"+r);
          text.innerHTML="Mismatched number of parts from the reference- Please make sure you have selected the right document";
          ref_table.style.display="none";
          document.getElementById("ref_score_"+ r).innerHTML =  "&#x274C";

      }
    }
  }
   

